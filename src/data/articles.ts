export function getArticleById(id: string | undefined): Article | undefined {
  return articles.find((article) => article.id === id);
}

export function getArticlesByPublication(publicationId: string): Article[] {
  return articles.filter((article) => article.publication === publicationId);
}

export function getArticlesByCategory(category: string): Article[] {
  return articles.filter((article) => article.category === category);
}

export function getFeaturedArticle(): Article {
  return articles[0];
}

export function getLatestArticles(count = 6): Article[] {
  return [...articles]
    .sort((a, b) => new Date(b.publishDate).getTime() - new Date(a.publishDate).getTime())
    .slice(0, count);
}

export function getCategories(): string[] {
  return [...new Set(articles.map((article) => article.category))];
}

